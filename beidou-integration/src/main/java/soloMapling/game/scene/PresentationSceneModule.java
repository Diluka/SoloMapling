package soloMapling.game.scene;

import org.gms.constants.game.CharacterStance;
import org.gms.net.server.Server;
import soloMapling.game.context.GameContext;
import soloMapling.game.context.NativeContextChecks;
import soloMapling.game.execution.ExecutionScope;

import java.util.concurrent.CancellationException;

/** Native output adaptation, called only inside the member's existing short lane work. */
public final class PresentationSceneModule implements SceneRuntimeModule {
    /** Turn before the native attack broadcast; normal attacks retain their own single output path. */
    public void faceAttack(SceneActorBinding binding, ExecutionScope.WorkHandle work, boolean facingLeft) {
        binding.requireCurrent();
        if (work.cancelRequested()) throw new CancellationException("scene_presentation_cancelled");
        var actor = binding.characterRef().character();
        if (actor.isAlive() && actor.isFacingLeft() != facingLeft) {
            actor.broadcastStance(facingLeft ? CharacterStance.STAND_LEFT_STANCE : CharacterStance.STAND_RIGHT_STANCE);
        }
    }

    /** Headless members supply the life-state movement input normally generated by the client. */
    public void syncLifeState(Server server, GameContext.SceneRef scene, ExecutionScope.WorkHandle work) {
        if (work.cancelRequested()) return;
        NativeContextChecks.requireSceneCurrent(server, scene);
        var actor = scene.actor().character();
        boolean alive = actor.isAlive();
        boolean deadPose = CharacterStance.isDead(actor.getStance());
        if (!alive && !deadPose) {
            actor.broadcastStance(actor.isFacingLeft() ? CharacterStance.DEAD_LEFT_STANCE : CharacterStance.DEAD_RIGHT_STANCE);
        } else if (alive && deadPose) {
            actor.broadcastStance(actor.isFacingLeft() ? CharacterStance.STAND_LEFT_STANCE : CharacterStance.STAND_RIGHT_STANCE);
        }
    }
}
